"""check_hourly_refs.py — audits references to `_hourly/` artifacts, and says which no longer exist.

Why. On 1 November the field line discovered that the evidence behind `E6c`/`E6d`/`E6e` (three plan sections, 36 per-run
files) lived in `_hourly/`, was never committed, and is gone. A sweep found the same pattern across the plan: many
sections cite `_hourly/<name>.json` as their machine check, and most of those files no longer exist and are not in the
log archive either.

This script does not fail the build — ninety-odd historical references cannot be "fixed" by editing history. It produces
the list, so a reader knows which numbers can still be checked from the repository and which cannot, and so that the
count does not grow silently.

    python scripts/check_hourly_refs.py --write      # regenerate docs/provenance-gaps.md
    python scripts/check_hourly_refs.py --ci         # fail only if the count grew past the recorded baseline

The baseline is stored in `docs/provenance-gaps.json`; `--ci` compares and fails on growth, which is the rule that
matters going forward: no new claim may rest on `_hourly/`.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "provenance-gaps.md"
BASELINE = ROOT / "docs" / "provenance-gaps.json"
PATTERN = re.compile(r"_hourly/[A-Za-z0-9_.*\-]+")


def scan() -> dict[str, list[str]]:
    """path token -> files that cite it; only tokens whose target does not exist."""
    missing: dict[str, list[str]] = {}
    sources = list((ROOT / "docs" / "plan").glob("*.md")) + list((ROOT / "reports").glob("*.md"))
    hourly = ROOT / "_hourly"
    for f in sources:
        text = f.read_text(encoding="utf-8")
        for m in PATTERN.finditer(text):
            token = m.group(0).rstrip(".,;")
            if "*" in token:
                exists = any(hourly.glob(token.split("/")[-1])) if hourly.exists() else False
            else:
                exists = (ROOT / token).exists()
            if not exists:
                missing.setdefault(token, [])
                rel = str(f.relative_to(ROOT)).replace("\\", "/")
                if rel not in missing[token]:
                    missing[token].append(rel)
    return dict(sorted(missing.items()))


def render(missing: dict[str, list[str]]) -> str:
    lines = [
        "# Provenance gaps: references to `_hourly/` artifacts that no longer exist",
        "",
        "Generated by `python scripts/check_hourly_refs.py --write`. The list is history, not a to-do: those files lived",
        "outside git and are not in the log archive. What it is for is the rule at the bottom — new claims cite",
        "`morphogenesis/experiments/`, never `_hourly/`.",
        "",
        f"**{len(missing)} references, in {len({f for fs in missing.values() for f in fs})} documents.**",
        "",
        "| reference | cited in |",
        "|---|---|",
    ]
    for token, files in missing.items():
        lines.append(f"| `{token}` | {', '.join(files[:3])}{' …' if len(files) > 3 else ''} |")
    lines += [
        "",
        "## What this means for a reader",
        "",
        "A number whose only trace is one of these paths can no longer be checked from the repository. Sections that also",
        "name an aggregate under `morphogenesis/experiments/` are fine: the aggregate is in git. Sections that name only",
        "`_hourly/` are not, and their numbers should be treated as reported rather than verified until the run is redone.",
        "",
        "## The rule that follows",
        "",
        "1. Per-run artifacts go to `morphogenesis/experiments/<line>/` and are committed; `_hourly/` is a scratch area.",
        "2. A section's *machine check* line names a path that exists in the repository, or says plainly that it does not.",
        "3. Long runs go through `scripts/lab.py run`, which writes a manifest; batch runners are the exception and must",
        "   say so (see `x60_series.py`, `e6p_series.py`).",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="audit lost _hourly artifact references")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--ci", action="store_true")
    args = ap.parse_args(argv)
    missing = scan()
    count = len(missing)
    if args.write:
        DOC.write_text(render(missing), encoding="utf-8", newline="\n")
        BASELINE.write_text(json.dumps({"count": count, "generated": "2026-11-01"}, indent=1) + "\n",
                            encoding="utf-8", newline="\n")
        print(f"[hourly-refs] written: {DOC.name} ({count} references)")
        return 0
    if args.ci:
        baseline = json.loads(BASELINE.read_text(encoding="utf-8"))["count"] if BASELINE.exists() else count
        if count > baseline:
            print(f"[hourly-refs] FAIL: {count} references, baseline {baseline} — new claims are citing _hourly/")
            return 1
        print(f"[hourly-refs] OK: {count} references, baseline {baseline}")
        return 0
    print(f"[hourly-refs] {count} references to missing files")
    for token, files in list(missing.items())[:10]:
        print(f"  {token}  <- {', '.join(files[:2])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
