"""attention.py — one page that answers "what needs a human, right now".

The laboratory has plenty of machine state (`health.md`, `queue.json`, `lit-board.json`), and that is exactly the problem:
a person reading it has to reconstruct which of forty items actually wants a decision. The page is deliberately small and
filtered:

1. **Needs the owner** — queue items marked `waiting_on: "owner"` plus everything the autonomy policy reserves to the owner;
2. **Running now** — items with status `running`, with the age of their last artifact;
3. **Waiting, but not on a human** — queued compute, ordered by cost;
4. **Stale** — planned items older than `--stale-days` and reports that are still plans after two days;
5. **Reviews not re-checked** — review files without a second pair of eyes;
6. **Board** — literature remarks still `new`.

`--write` regenerates `lab/ATTENTION.md`; `--check` verifies that every owner item, every running item and every new board
remark is mentioned by id. The check is structural on purpose: ages change between machines, ids do not.
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lab" / "ATTENTION.md"
QUEUE = ROOT / "lab" / "queue.json"
BOARD = ROOT / "lab" / "lit-board.json"
REVIEWS = ROOT / "lab" / "reviews"
REPORTS = ROOT / "reports"
RULES = ROOT / "lab" / "autonomy-rules.json"


def load_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default


def age_days(stamp: str | None, today: dt.date) -> int | None:
    if not stamp:
        return None
    m = re.match(r"(\d{4})-(\d{2})-(\d{2})", stamp)
    if not m:
        return None
    try:
        d = dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    except ValueError:
        return None
    return (today - d).days


def queue_parts(today: dt.date):
    q = load_json(QUEUE, {"items": []})
    items = q.get("items") or []
    owner, running, waiting, stale = [], [], [], []
    for it in items:
        status = it.get("status")
        if status == "running":
            running.append(it)
        elif status == "planned":
            if str(it.get("waiting_on") or "").lower() in ("owner", "владелец"):
                owner.append(it)
            else:
                (stale if (age_days(it.get("created_at"), today) or 0) > 14 else waiting).append(it)
    return owner, running, waiting, stale, items


def newest_artifact_age_hours() -> float | None:
    files = glob.glob(str(ROOT / "morphogenesis" / "experiments" / "**" / "*.json"), recursive=True)
    if not files:
        return None
    newest = max(Path(f).stat().st_mtime for f in files)
    return (dt.datetime.now().timestamp() - newest) / 3600.0


def plan_reports(today: dt.date) -> list[tuple[str, int]]:
    rows = []
    for f in sorted(REPORTS.glob("*-plan.md")):
        m = re.match(r"(\d{4})-(\d{2})-(\d{2})", f.name)
        if not m:
            continue
        d = dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
        days = (today - d).days
        if days >= 1:
            rows.append((f.name, days))
    return rows


def unrevised_reviews() -> list[str]:
    out = []
    for f in sorted(REVIEWS.glob("*.md")):
        if f.name == "README.md":
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        if "Перепроверено ведущим" not in text and "re-checked by the lead" not in text.lower():
            out.append(f.name)
    return out


def build(today: dt.date) -> str:
    rules = load_json(RULES, {})
    owner, running, waiting, stale, items = queue_parts(today)
    board = load_json(BOARD, {"items": []}).get("items") or []
    board_new = [b for b in board if b.get("status") == "new"]
    plans = plan_reports(today)
    reviews = unrevised_reviews()
    age_h = newest_artifact_age_hours()

    lines: list[str] = []
    lines.append("# What needs a human")
    lines.append("")
    lines.append("Generated by `scripts/attention.py --write`. Machine state is in `reports/health.md`, the queue in "
                 "`lab/queue.json`; this page only filters what a person has to decide.")
    lines.append("")
    lines.append("## Needs the owner")
    lines.append("")
    if owner:
        for it in owner:
            age = age_days(it.get("created_at") or it.get("started_at"), today)
            age_s = f", waiting {age} d" if age is not None else ""
            lines.append(f"- **{it.get('id')}** — {it.get('title')}{age_s}. {it.get('note', '')}".rstrip())
    else:
        lines.append("- nothing")
    lines.append("")
    lines.append("Reserved to the owner by `lab/autonomy-rules.json`: "
                 + "; ".join(rules.get("requires_owner") or []) + ".")
    lines.append("")
    lines.append("## Running now")
    lines.append("")
    if running:
        for it in running:
            lines.append(f"- **{it.get('id')}** — {it.get('title')} (owner `{it.get('owner')}`)")
        if age_h is not None:
            lines.append(f"- last artifact written {age_h:.1f} h ago")
    else:
        lines.append("- nothing is running")
    lines.append("")
    lines.append("## Waiting, but not on a human")
    lines.append("")
    if waiting:
        for it in sorted(waiting, key=lambda x: float(x.get("cost_gpu_h") or 0.0)):
            cost = it.get("cost_gpu_h")
            cost_s = f"{cost} GPU-h" if cost else "no GPU"
            lines.append(f"- **{it.get('id')}** — {it.get('title')} ({cost_s})")
    else:
        lines.append("- nothing queued")
    lines.append("")
    lines.append("## Stale")
    lines.append("")
    if stale or plans:
        for it in stale:
            lines.append(f"- queue item **{it.get('id')}** planned for more than 14 days: {it.get('title')}")
        for name, days in plans:
            lines.append(f"- preregistration without a result for {days} d: `reports/{name}`")
    else:
        lines.append("- nothing older than the thresholds")
    lines.append("")
    lines.append("## Reviews not re-checked")
    lines.append("")
    lines.append("\n".join(f"- `lab/reviews/{r}`" for r in reviews) if reviews else "- every review has a second pair of eyes")
    lines.append("")
    lines.append("## Literature board")
    lines.append("")
    lines.append("\n".join(f"- **{b.get('id')}** — {b.get('statement', '')[:120]}" for b in board_new)
                 if board_new else "- no new remarks")
    lines.append("")
    lines.append("## How this page stays honest")
    lines.append("")
    lines.append("`python scripts/attention.py --check` fails if an owner item, a running item or a new board remark is not "
                 "mentioned here, so the page cannot silently lose a decision. Ages are recomputed on every write; the "
                 "check is structural, because dates differ between machines and ids do not.")
    lines.append("")
    return "\n".join(lines)


def check() -> list[str]:
    today = dt.date.today()
    text = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    problems: list[str] = []
    if not text:
        return ["нет lab/ATTENTION.md — соберите: python scripts/attention.py --write"]
    owner, running, _waiting, _stale, _items = queue_parts(today)
    for it in owner + running:
        if str(it.get("id")) not in text:
            problems.append(f"пункт {it.get('id')} не упомянут на странице внимания")
    board_new = [b for b in (load_json(BOARD, {"items": []}).get("items") or []) if b.get("status") == "new"]
    for b in board_new:
        if str(b.get("id")) not in text:
            problems.append(f"замечание доски {b.get('id')} не упомянуто")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="attention page")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    if args.write:
        OUT.write_text(build(dt.date.today()), encoding="utf-8", newline="\n")
        print(f"[attention] written: {OUT.name}")
        return 0
    if args.check:
        problems = check()
        for p in problems:
            print(f"  ПРОВАЛ: {p}")
        print(f"[attention] проблем: {len(problems)}")
        return 1 if problems else 0
    print(build(dt.date.today())[:2000])
    return 0


if __name__ == "__main__":
    sys.exit(main())
