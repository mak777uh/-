import json, os, subprocess, sys

MORPH = "/content/repo/morphogenesis"
SEEDS = [101, 142, 202, 242, 303]

import torch
print("torch:", torch.__version__, "| cuda:", torch.version.cuda,
      "| gpu:", torch.cuda.get_device_name(0), flush=True)

for s in SEEDS:
    fam  = f"E02c_R-9_s2000_seed{s}"
    ckpt = f"{MORPH}/checkpoints/{fam}/nca_final.pt"
    summ = f"/content/summary_colab_seed{s}.json"

    if not os.path.exists(ckpt):
        print(f"=== seed {s}: обучение ===", flush=True)
        r = subprocess.run([sys.executable, "e02c_replication.py",
                            "--seed", str(s), "--steps", "2000"], cwd=MORPH)
        if r.returncode != 0:
            print(f"обучение упало на seed {s}, иду дальше", flush=True); continue

    if not os.path.exists(summ):
        print(f"=== seed {s}: перепись ===", flush=True)
        r = subprocess.run([sys.executable, "e02c_census.py",
                            "--seeds", "0-63", "--steps", "2000",
                            "--families", fam, "--allow-missing-control",
                            "--out", f"/content/census_colab_seed{s}.json",
                            "--summary-out", summ], cwd=MORPH)
        if r.returncode != 0:
            print(f"перепись упала на seed {s}", flush=True); continue

    d = json.load(open(summ))
    for f, st in d["stats"].items():
        print(f"  seed {s}: {f} struct_2 {st['struct_2']}/{st['n']} "
              f"{st['frozen_class_counts']}", flush=True)

    for pat in ("nca_iter_1000.pt", "nca_iter_2000.pt", "nca_best.pt"):
        p = f"{MORPH}/checkpoints/{fam}/{pat}"
        if os.path.exists(p):
            os.remove(p)

print("=== скрининг завершён ===", flush=True)